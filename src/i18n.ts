const DICOS: Record<Langue, Dico> = { fr, en };

export function langue(): Langue {
  return lireEtat().langue;
}

/** Traduit une clé ; {nom} est remplacé par la valeur correspondante. Repli sur le français. */
export function t(cle: string, vars: Record<string, string | number> = {}): string {
  const brut = DICOS[langue()][cle] ?? fr[cle] ?? cle;
  return brut.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

/** Liste séparée par des barres verticales (choix de quiz, notions). */
export function tListe(cle: string): string[] {
  return t(cle).split('|');
}

/** Vérifie qu'aucune clé ne manque dans une langue (utilisé par les tests). */
export function clesManquantes(): { langue: Langue; cle: string }[] {
  const manques: { langue: Langue; cle: string }[] = [];
  for (const l of Object.keys(DICOS) as Langue[]) {
    for (const cle of Object.keys(fr)) if (!(cle in DICOS[l])) manques.push({ langue: l, cle });
    for (const cle of Object.keys(DICOS[l])) if (!(cle in fr)) manques.push({ langue: 'fr', cle });
  }
  return manques;
}
